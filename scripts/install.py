#!/usr/bin/env python3
"""Build and install Waylauncher.app (the MyGo application) into ~/Applications.

    python3 scripts/install.py                # build + install Waylauncher.app
    python3 scripts/install.py --legacy-swift # build the old Swift launcher instead

Any existing Waylauncher.app is moved to
~/Library/Application Support/Waylauncher/Backups/<timestamp>/ first. Profiles,
settings and logs are never touched by the installer (the per-application Dock
bundles in ~/Applications/Waylauncher Apps are generated by the app itself,
with their own backups); the legacy
~/.config/vm200-launcher/profiles.json is only read, and only by the app on
its first start.
"""
import argparse
import datetime
import os
from pathlib import Path
import plistlib
import shutil
import subprocess
import sys
import tempfile

root = Path(__file__).resolve().parent.parent
home = Path.home()
VERSION = "0.1.0"
BUNDLE_ID = "com.keiko233.waylauncher"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--legacy-swift", action="store_true",
                    help="build and install the legacy Swift launcher (scripts/legacy-swift-install.py) instead")
    ap.add_argument("--dest", type=Path, default=home / "Applications",
                    help="directory to install into (default ~/Applications)")
    ap.add_argument("--backup-dir", type=Path,
                    default=home / "Library/Application Support/Waylauncher/Backups",
                    help="where a replaced bundle is moved")
    args = ap.parse_args()
    if os.uname().sysname != "Darwin":
        raise SystemExit("This installer requires macOS")
    if args.legacy_swift:
        os.execv(sys.executable, [sys.executable, str(root / "scripts/legacy-swift-install.py")])
    install(args)


def run(cmd, **kw):
    return subprocess.run([str(c) for c in cmd], check=True, **kw)


def make_icns(out: Path, work: Path):
    iconset = work / "Waylauncher.iconset"
    iconset.mkdir()
    for size, name in [(16, "icon_16x16"), (32, "icon_16x16@2x"), (32, "icon_32x32"), (64, "icon_32x32@2x"),
                       (128, "icon_128x128"), (256, "icon_128x128@2x"), (256, "icon_256x256"),
                       (512, "icon_256x256@2x"), (512, "icon_512x512"), (1024, "icon_512x512@2x")]:
        run(["go", "run", "./scripts/genicon", size, iconset / (name + ".png")], cwd=root)
    run(["iconutil", "-c", "icns", iconset, "-o", out])


def install(args):
    dest, backup_root = args.dest, args.backup_dir
    dest.mkdir(parents=True, exist_ok=True)
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S-%f")
    with tempfile.TemporaryDirectory(prefix="waylauncher-build-") as tmp:
        tmp = Path(tmp)
        app = tmp / "Waylauncher.app"
        contents = app / "Contents"
        (contents / "MacOS").mkdir(parents=True)
        (contents / "Resources").mkdir()

        # Pure Go (no cgo). go.mod pins Go 1.27.3; GOTOOLCHAIN=auto fetches it when needed.
        env = dict(os.environ, CGO_ENABLED="0")
        run(["go", "build", "-trimpath", "-ldflags", f"-s -w -X main.version={VERSION}",
             "-o", contents / "MacOS/waylauncher", "./cmd/waylauncher"], cwd=root, env=env)
        # The Dock helper: copied into one generated bundle per application at run time.
        run(["go", "build", "-trimpath", "-ldflags", f"-s -w -X main.version={VERSION}",
             "-o", contents / "Resources/waylauncher-dock-helper", "./cmd/waylauncher-dock-helper"], cwd=root, env=env)
        make_icns(contents / "Resources/Waylauncher.icns", tmp)

        info = dict(
            CFBundleIdentifier=BUNDLE_ID, CFBundleName="Waylauncher", CFBundleDisplayName="Waylauncher",
            CFBundleExecutable="waylauncher", CFBundlePackageType="APPL", CFBundleIconFile="Waylauncher",
            CFBundleShortVersionString=VERSION, CFBundleVersion=VERSION,
            LSMinimumSystemVersion="12.0", NSHighResolutionCapable=True,
            LSApplicationCategoryType="public.app-category.utilities",
            # Release behaviour of MyGo (no web inspector) for this go build.
            LSEnvironment={"MYGO_ENV": "production"},
            NSLocalNetworkUsageDescription="Connect to your Linux machine over SSH to display its applications.",
            CFBundleURLTypes=[dict(CFBundleURLName="Waylauncher links", CFBundleURLSchemes=["waylauncher"])],
        )
        (contents / "Info.plist").write_bytes(plistlib.dumps(info))

        target = dest / "Waylauncher.app"
        if target.exists():
            backup = backup_root / stamp
            backup.mkdir(parents=True, exist_ok=True)
            shutil.move(str(target), str(backup / target.name))
            print(f"Previous bundle moved to {backup / target.name}")
        shutil.copytree(app, target, symlinks=True)
        run(["codesign", "--force", "--sign", "-", target])

    exe = target / "Contents/MacOS/waylauncher"
    # Read-only validation: a dry run never writes or migrates anything.
    if subprocess.run([str(exe), "--check-config", "--dry-run"]).returncode != 0:
        print("Warning: the configuration check above reported a problem; the app is installed anyway.")
    print(f"Installed {target}")


if __name__ == "__main__":
    main()
